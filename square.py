def area(a):
    """Площадь квадрата со стороной a: a ** 2.

    a - положительное число; результат - число, квадратные единицы.
    Аргументы не проверяются; корректность размеров обеспечивает вызывающий код.

    >>> area(3)
    9
    """
    return a * a


def perimeter(a):
    """Периметр квадрата со стороной a: 4 * a.

    a - положительное число; результат - число, единицы длины.
    Аргументы не проверяются; корректность размеров обеспечивает вызывающий код.

    >>> perimeter(3)
    12
    """
    return 4 * a
