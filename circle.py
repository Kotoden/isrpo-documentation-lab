import math


def area(r):
    """Площадь круга по радиусу r: pi * r ** 2.

    r - положительное число; результат - float, квадратные единицы.
    Аргументы не проверяются; корректность размеров обеспечивает вызывающий код.

    >>> round(area(2), 5)
    12.56637
    """
    return math.pi * r * r


def perimeter(r):
    """Длина окружности по радиусу r: 2 * pi * r.

    r - положительное число; результат - float, единицы длины.
    Аргументы не проверяются; корректность размеров обеспечивает вызывающий код.

    >>> round(perimeter(2), 5)
    12.56637
    """
    return 2 * math.pi * r
