def area(a, h):
    """Площадь треугольника по основанию a и высоте h к нему: a * h / 2.

    a, h - положительные числа; результат - float, квадратные единицы.
    Аргументы не проверяются; корректность размеров обеспечивает вызывающий код.

    >>> area(4, 3)
    6.0
    """
    return a * h / 2


def perimeter(a, b, c):
    """Периметр треугольника: a + b + c.

    a, b, c - положительные стороны существующего треугольника.
    Аргументы не проверяются; корректность размеров обеспечивает вызывающий код.

    >>> perimeter(3, 4, 5)
    12
    """
    return a + b + c
