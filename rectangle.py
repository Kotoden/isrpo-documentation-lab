def area(a, b):
    """Площадь прямоугольника со сторонами a и b: a * b.

    a, b - положительные числа; результат - число, квадратные единицы.
    Аргументы не проверяются; корректность размеров обеспечивает вызывающий код.

    >>> area(3, 4)
    12
    """
    return a * b


def perimeter(a, b):
    """Периметр прямоугольника со сторонами a и b: 2 * (a + b).

    a, b - положительные числа; результат - число, единицы длины.
    Аргументы не проверяются; корректность размеров обеспечивает вызывающий код.

    >>> perimeter(3, 4)
    14
    """
    return 2 * (a + b)
